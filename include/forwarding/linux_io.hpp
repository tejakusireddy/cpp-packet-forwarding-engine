#pragma once

#include <cstddef>
#include <cstdint>
#include <optional>
#include <span>
#include <string_view>

namespace forwarding {

// Linux AF_PACKET reference backend. Requires CAP_NET_RAW. Nonblocking and
// allocation-free after construction; owns its socket and is not copyable.
class PacketSocket {
public:
    explicit PacketSocket(std::string_view interface);
    ~PacketSocket();
    PacketSocket(const PacketSocket&) = delete;
    PacketSocket& operator=(const PacketSocket&) = delete;
    PacketSocket(PacketSocket&&) = delete;
    PacketSocket& operator=(PacketSocket&&) = delete;
    [[nodiscard]] unsigned interface_id() const noexcept { return interface_id_; }
    [[nodiscard]] std::size_t mtu() const noexcept { return mtu_; }
    // Empty on EAGAIN or an outgoing copy. Oversized input throws length_error.
    [[nodiscard]] std::optional<std::size_t> receive(std::span<std::uint8_t> buffer);
    // Returns false under socket backpressure. Enforces MTU and supplies zero
    // padding to 60 Ethernet bytes (FCS is generated by the device).
    [[nodiscard]] bool transmit(std::span<const std::uint8_t> frame);

private:
    int socket_ = -1;
    unsigned interface_id_ = 0;
    std::size_t mtu_ = 0;
};

// Optional Linux affinity. Throws system_error if the requested CPU is not in
// the process's permitted CPU set; callers must use the actual allowed CPU IDs.
void pin_current_thread(unsigned cpu);

} // namespace forwarding
